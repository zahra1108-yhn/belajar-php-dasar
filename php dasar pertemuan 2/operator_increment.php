<?php
  // Menyiapkan nilai variabel awal
  $a = 25;

  // 1. Operator Increment (++) -> Menambah 1 ke nilai variabel
  $a++; // Nilai $a bertambah 1 menjadi 26
  echo $a . "<br>"; // Output: 26

  // 2. Operator Decrement (--) -> Mengurangi 1 dari nilai variabel
  $a--; // Nilai $a berkurang 1 kembali menjadi 25
  echo $a . "<br>"; // Output: 25

  // Contoh tambahan: Decrement sekali lagi
  $a--; // Nilai $a berkurang 1 lagi menjadi 24
  echo $a . "<br>"; // Output: 24
?>